"""Independent, labeled Scanner fixture gap evaluation using scikit-learn 1.8.

Offline evaluation ONLY: the real ScannerGateway produces all observations.
scikit-learn computes confusion and classification metrics; it never decides
readiness or authorizes a Runtime effect. Fixture labels are predefined,
not generated by Scanner output or learned from it.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from tempfile import TemporaryDirectory

from pydantic import BaseModel
from sklearn import __version__ as sklearn_version
from sklearn.metrics import classification_report, confusion_matrix

from agent.contracts.common import ArtifactRef
from agent.contracts.scanner import ScannerOutcome
from agent.runtime.artifact_store import ArtifactStore
from agent.runtime.scanner_gateway import ScannerGateway


class Candidate(BaseModel):
    actions: list[dict[str, object]]


class MalformedCandidate(BaseModel):
    data: str


@dataclass(frozen=True)
class Case:
    name: str
    expected: str
    actions: tuple[tuple[str, tuple[str, ...]], ...] = ()
    evidence: str = "verified"
    capabilities: tuple[str, ...] = ("dependency_readiness",)


CASES = (
    Case("clear_single", "clear", (("a", ()),)),
    Case("clear_independent", "clear", (("a", ()), ("b", ()))),
    Case("clear_chain", "clear", (("a", ()), ("b", ("a",)), ("c", ("b",)))),
    Case("clear_diamond", "clear", (("a", ()), ("b", ("a",)), ("c", ("a",)), ("d", ("b", "c")))),
    Case("clear_long_chain", "clear", tuple((f"a{i}", (f"a{i - 1}",) if i else ()) for i in range(40))),
    Case("missing_single", "defect", (("a", ()), ("b", ("missing",)))),
    Case("missing_multiple", "defect", (("a", ("x", "y")), ("b", ()))),
    Case("missing_mixed", "defect", (("a", ()), ("b", ("a", "missing")))),
    Case("self_cycle", "defect", (("a", ("a",)),)),
    Case("two_node_cycle", "defect", (("a", ("b",)), ("b", ("a",)))),
    Case("three_node_cycle", "defect", (("a", ("b",)), ("b", ("c",)), ("c", ("a",)))),
    Case("cycle_and_missing", "defect", (("a", ("b", "none")), ("b", ("a",)))),
    Case("duplicate_id", "defect", (("a", ()), ("a", ()))),
    Case("duplicate_with_consumer", "defect", (("a", ()), ("a", ()), ("b", ("a",)))),
    Case("missing_artifact", "unknown", (("a", ()),), evidence="missing"),
    Case("digest_mismatch", "unknown", (("a", ()),), evidence="mismatch"),
    Case("malformed_candidate", "unknown", evidence="malformed"),
    Case("no_actions", "unknown", evidence="empty"),
    Case("unsupported_capability", "unknown", (("a", ()),), capabilities=("nonexistent_detector",)),
    Case("no_capability_requested", "unknown", (("a", ()),), capabilities=()),
)

LABELS = ("clear", "defect", "unknown")


def classify(result) -> str:
    """Translate the actual Scanner result into independently scored outcomes."""
    if result.findings or any(step.criterion_result.value == "not_satisfied" for step in result.trace_steps):
        return "defect"
    if result.outcome is ScannerOutcome.PASS:
        return "clear"
    return "unknown"


def run_fixture(case: Case, root: Path) -> tuple[str, dict[str, object]]:
    store = ArtifactStore(root)
    gateway = ScannerGateway(store)
    artifact_id = f"fixture-{case.name}"
    if case.evidence == "missing":
        digest = "a" * 64
    elif case.evidence == "malformed":
        digest = store.put_immutable(MalformedCandidate(data="not an action graph"), artifact_id, 1, "planning", "1.0")
    else:
        actions = [{"action_id": action_id, "depends_on": list(deps)} for action_id, deps in case.actions]
        digest = store.put_immutable(Candidate(actions=actions), artifact_id, 1, "planning", "1.0")
    if case.evidence == "mismatch":
        digest = "0" * 64 if digest != "0" * 64 else "f" * 64
    ref = ArtifactRef(
        artifact_id=artifact_id,
        artifact_revision=1,
        artifact_digest=digest,
        contract_id="planning",
        contract_version="1.0",
        serializer_profile="rfc8785-jcs-sha256-v1",
    )
    result = gateway.scan_exact(ref, "fixture-repository", case.capabilities)
    return classify(result), {
        "case": case.name,
        "expected": case.expected,
        "observed": classify(result),
        "execution_outcome": result.outcome.value,
        "findings": [finding.finding_id for finding in result.findings],
        "not_checked": list(result.capabilities_not_checked),
        "checked": list(result.capabilities_checked),
    }


def main() -> int:
    with TemporaryDirectory(prefix="oneshot-sklearn-gap-") as folder:
        observations = [run_fixture(case, Path(folder)) for case in CASES]

    actual = [item[0] for item in observations]
    expected = [case.expected for case in CASES]
    report = classification_report(expected, actual, labels=list(LABELS), output_dict=True, zero_division=0)
    matrix = confusion_matrix(expected, actual, labels=list(LABELS))
    mismatches = [details for predicted, details in observations if predicted != details["expected"]]
    # Classification must also expose structural false claims, not only headline labels.
    incorrect_checked = [
        details for _, details in observations if details["case"] == "unsupported_capability" and details["checked"]
    ]
    payload = {
        "evaluation": "fixture_only_not_build_probability",
        "scikit_learn_version": sklearn_version,
        "labels": list(LABELS),
        "fixtures": len(CASES),
        "confusion_matrix": matrix.tolist(),
        "classification_report": report,
        "mismatches": mismatches,
        "incorrect_checked": incorrect_checked,
    }
    print(json.dumps(payload, sort_keys=True))
    return 1 if mismatches or incorrect_checked else 0


if __name__ == "__main__":
    raise SystemExit(main())
